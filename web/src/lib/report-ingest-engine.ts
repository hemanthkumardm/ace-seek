// Ingest entry point
// ---------------------------------------------------------------------------

export function ingestReport(
  text: string,
  vendorHint: TimingVendor = "auto"
): IngestResult {
  const warnings: string[] = [];
  if (!text || !text.trim()) {
    return {
      kind: "unknown",
      vendor: "auto",
      detectedVendor: "synopsys",
      tool: "Unknown",
      stage: "unknown",
      rawBlocks: [],
      warnings: ["Empty report text provided."],
      isPs: false,
      headerLines: [],
      totalRawLines: 0,
    };
  }

  const detectedVendor = detectVendor(text);
  const effectiveVendor = vendorHint === "auto" ? detectedVendor : vendorHint;
  const tool = detectTool(text, effectiveVendor);

  let designName: string | undefined;
  let operatingConditions: string | undefined;
  let wireloadMode: string | undefined;
  let areaMode: string | undefined;

  const moduleMatch =
    text.match(/Module:\s*(\S+)/i) ||
    text.match(/Design\s*:\s*(\S+)/i) ||
    text.match(/Design\s+name\s*[:=]\s*(\S+)/i) ||
    text.match(/Block\s*[:=]\s*(\S+)/i) ||
    text.match(/Top\s*(?:module|cell)\s*[:=]\s*(\S+)/i);
  if (moduleMatch) designName = moduleMatch[1].trim().replace(/[,"']+$/g, "");

  const opMatch = text.match(/Operating conditions:\s*(.*)/i);
  if (opMatch) operatingConditions = opMatch[1].trim();

  const wlMatch = text.match(/Wireload mode:\s*(.*)/i);
  if (wlMatch) wireloadMode = wlMatch[1].trim();

  const areaMatch = text.match(/Area mode:\s*(.*)/i);
  if (areaMatch) areaMode = areaMatch[1].trim();

  const stage = detectFlowStage(tool, text, wireloadMode);
  const kind = detectReportKind(text);
  const isPs = detectIsPs(text);

  const lines = text.split("\n");
  const headerLines = lines.slice(0, 15).filter((l) => l.trim().startsWith("#") || l.includes(":") || l.includes("="));

  const rawBlocks = splitReportIntoBlocks(text, effectiveVendor);
  if (rawBlocks.length === 0) {
    warnings.push("No distinct timing path blocks found in report.");
  }

  return {
    kind,
    vendor: effectiveVendor,
    detectedVendor,
    tool,
    designName,
    operatingConditions,
    wireloadMode,
    areaMode,
    stage,
    rawBlocks,
    warnings,
    isPs,
    headerLines,
    totalRawLines: lines.length,
  };
}

// ---------------------------------------------------------------------------
// Multi-File Session Management
// ---------------------------------------------------------------------------

export function createReportSession(
  initialText?: string,
  filename = "report_1.rpt",
  vendorHint: TimingVendor = "auto"
): ReportSession {
  if (!initialText || !initialText.trim()) {
    return { files: [], activeId: "" };
  }
  const result = ingestReport(initialText, vendorHint);
  const file: IngestReportFile = {
    id: `file_${Date.now()}_1`,
    filename,
    text: initialText,
    parsedAt: Date.now(),
    result,
  };
  return {
    files: [file],
    activeId: file.id,
  };
}

export function addReportFile(
  session: ReportSession,
  filename: string,
  text: string,
  vendorHint: TimingVendor = "auto"
): ReportSession {
  const result = ingestReport(text, vendorHint);
  const file: IngestReportFile = {
    id: `file_${Date.now()}_${session.files.length + 1}`,
    filename,
    text,
    parsedAt: Date.now(),
    result,
  };
  return {
    files: [...session.files, file],
    activeId: file.id,
  };
}

export function switchActiveFile(
  session: ReportSession,
  fileId: string
): ReportSession {
  if (!session.files.some((f) => f.id === fileId)) return session;
  return {
    ...session,
    activeId: fileId,
  };
}

export function removeReportFile(
  session: ReportSession,
  fileId: string
): ReportSession {
  const files = session.files.filter((f) => f.id !== fileId);
  const activeId =
    session.activeId === fileId
      ? files.length > 0
        ? files[files.length - 1].id
        : ""
      : session.activeId;
  return { files, activeId };
}

export function getActiveFile(
  session: ReportSession
): IngestReportFile | undefined {
  return session.files.find((f) => f.id === session.activeId);
}
