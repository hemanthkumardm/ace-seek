/**
 * Unified Report Ingest Engine for VLSI Studios.
 *
 * Single entry point for pasting/uploading any STA or constraint report.
 * Provides vendor auto-detection, tool metadata extraction, flow stage classification,
 * block splitting registry, and multi-file session management.
 */

import { parseTimeToken } from "./timing-engine";
import { extractCornerFromBlock } from "./corner-model";

export type TimingVendor = "synopsys" | "cadence" | "opensta" | "auto";
export type FlowStage = "synthesis" | "pnr" | "signoff" | "unknown";
export type ReportKind = "timing_path" | "si_crosstalk" | "summary_only" | "unknown";

export interface RawReportBlock {
  id: string;
  rawText: string;
  blockIndex: number;
  kind: "path" | "summary" | "header" | "unknown";
  headerHint?: {
    startpoint?: string;
    endpoint?: string;
    pathGroup?: string;
    type?: "setup" | "hold";
    clock?: string;
    corner?: string;
  };
}

export interface IngestResult {
  kind: ReportKind;
  vendor: TimingVendor;
  detectedVendor: TimingVendor;
  tool: string;
  designName?: string;
  operatingConditions?: string;
  wireloadMode?: string;
  areaMode?: string;
  stage: FlowStage;
  rawBlocks: RawReportBlock[];
  warnings: string[];
  isPs: boolean;
  headerLines: string[];
  totalRawLines: number;
}

export interface IngestReportFile {
  id: string;
  filename: string;
  text: string;
  parsedAt: number;
  result: IngestResult;
}

export interface ReportSession {
  files: IngestReportFile[];
  activeId: string;
}

